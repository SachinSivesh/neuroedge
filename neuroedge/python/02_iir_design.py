"""Step 2: design the 8-30 Hz IIR band-pass for the FPGA.

Produces:
  rtl/params/iir_coeffs.vh   Verilog localparams for the biquad coefficients
  vectors/iir_in.hex         8-channel test input (16-bit, frame by frame)
  vectors/iir_out.hex        expected output from the bit-exact integer model
  results/02_iir_response.png   float vs fixed-point frequency response

The Verilog filter (rtl/iir_bandpass.v) must reproduce iir_out.hex exactly;
tb/tb_iir.v checks this.  Arithmetic per biquad (Direct Form I):
    acc  = b0*x + b1*x1 + b2*x2 - a1*y1 - a2*y2          (IIR_ACC_W bits)
    y    = sat_INT_W((acc + 2^(FRAC-1)) >>> FRAC)
Input is shifted up by 8 guard bits before the first section and rounded
back down to 16 bits after the last.  No dataset needed for this script.
"""
from pathlib import Path

import numpy as np
from scipy import signal
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from neuroedge import config as cfg, fixed as fx

ROOT = Path(__file__).resolve().parent.parent
FS = 250
N_FRAMES = 1000


def test_input():
    """Tones at 3, 12, 20, 50 Hz plus noise; each channel phase-shifted so the
    testbench also proves the 8 channel states never mix."""
    rng = np.random.default_rng(0)
    t = np.arange(N_FRAMES + 8 * 37) / FS
    x = (np.sin(2 * np.pi * 3 * t) + np.sin(2 * np.pi * 12 * t)
         + 0.8 * np.sin(2 * np.pi * 20 * t) + 0.8 * np.sin(2 * np.pi * 50 * t)
         + 0.5 * rng.normal(size=t.size))
    x = x / np.abs(x).max() * 0.8 * (1 << (cfg.DATA_W - 1))
    frames = np.stack([x[37 * c: 37 * c + N_FRAMES] for c in range(cfg.N_CH)], axis=1)
    return np.round(frames).astype(np.int64)


def to_hex(vals, width):
    digits = (width + 3) // 4
    return "\n".join(f"{int(v) & ((1 << width) - 1):0{digits}X}" for v in vals) + "\n"


def write_coeffs(q, path):
    lines = [
        "// Auto-generated by python/02_iir_design.py -- do not edit by hand",
        f"// Butterworth band-pass {cfg.IIR_BAND[0]}-{cfg.IIR_BAND[1]} Hz at fs = {FS} Hz",
        f"// y = sat((b0*x + b1*x1 + b2*x2 - a1*y1 - a2*y2 + 2^{cfg.IIR_FRAC - 1}) >>> {cfg.IIR_FRAC})",
        f"localparam integer IIR_COEF_W = {cfg.IIR_COEF_W};",
        f"localparam integer IIR_FRAC   = {cfg.IIR_FRAC};",
        f"localparam integer IIR_INT_W  = {cfg.IIR_INT_W};",
        f"localparam integer IIR_ACC_W  = {cfg.IIR_ACC_W};",
    ]
    for i, (b0, b1, b2, _, a1, a2) in enumerate(q.tolist()):
        for name, v in (("B0", b0), ("B1", b1), ("B2", b2), ("A1", a1), ("A2", a2)):
            sign = "-" if v < 0 else ""
            lines.append(f"localparam signed [{cfg.IIR_COEF_W - 1}:0] S{i}_{name} = "
                         f"{sign}{cfg.IIR_COEF_W}'sd{abs(v)};")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main():
    sos, q = fx.iir_design()
    assert len(q) == 2, "rtl/iir_bandpass.v has exactly 2 sections"
    print(f"Butterworth band-pass {cfg.IIR_BAND[0]}-{cfg.IIR_BAND[1]} Hz, fs={FS} Hz, {len(q)} biquads")
    print(f"Coefficients: {cfg.IIR_COEF_W}-bit signed, {cfg.IIR_FRAC} fractional bits")
    for i, row in enumerate(q):
        print(f"  section {i}: b = {row[:3].tolist()}  a1, a2 = {row[4:].tolist()}")

    w, h = signal.sosfreqz(sos, worN=2048, fs=FS)
    _, hq = signal.sosfreqz(q / (1 << cfg.IIR_FRAC), worN=2048, fs=FS)
    db = lambda v: 20 * np.log10(np.maximum(np.abs(v), 1e-9))
    for f in (3, 8, 12, 20, 30, 50):
        k = np.argmin(np.abs(w - f))
        print(f"  {f:>3} Hz: float {db(h[k]):6.1f} dB   fixed {db(hq[k]):6.1f} dB")

    x = test_input()
    y_fix = fx.iir_stream(x, q)
    y_flt = signal.sosfilt(sos, x.astype(float), axis=0)
    err = y_fix - y_flt
    snr = 10 * np.log10(np.sum(y_flt ** 2) / np.sum(err ** 2))
    print(f"Fixed-point vs float output SNR: {snr:.1f} dB (want > 60 dB)")

    (ROOT / "vectors").mkdir(exist_ok=True)
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "vectors" / "iir_in.hex").write_text(to_hex(x.ravel(), cfg.DATA_W))
    (ROOT / "vectors" / "iir_out.hex").write_text(to_hex(y_fix.ravel(), cfg.DATA_W))
    write_coeffs(q, ROOT / "rtl" / "params" / "iir_coeffs.vh")

    fig, (a, b) = plt.subplots(2, 1, figsize=(7, 6))
    a.plot(w, db(h), label="float")
    a.plot(w, db(hq), "--", label=f"fixed ({cfg.IIR_COEF_W}-bit coefficients)")
    a.axvspan(*cfg.IIR_BAND, alpha=0.1)
    a.set_ylim(-80, 5)
    a.set_xlabel("Hz")
    a.set_ylabel("dB")
    a.set_title("8-30 Hz band-pass")
    a.legend()
    n = 500
    b.plot(np.arange(n) / FS, y_flt[:n, 0], label="float")
    b.plot(np.arange(n) / FS, y_fix[:n, 0], "--", label="bit-exact integer model")
    b.set_xlabel("s")
    b.set_title(f"Test signal through the filter, channel 0 (SNR {snr:.0f} dB)")
    b.legend()
    fig.tight_layout()
    fig.savefig(ROOT / "results" / "02_iir_response.png", dpi=130)
    print("Wrote rtl/params/iir_coeffs.vh, vectors/iir_in.hex, vectors/iir_out.hex, "
          "results/02_iir_response.png")


if __name__ == "__main__":
    main()
