"""Step 6: the complete integer hardware model, and its export to the RTL.

1. For every subject at K = K_DEFAULT: train on day 1, decode day 2 with the
   full NeuroEdge policy, and compare against a floating-point version of the
   same decoder to measure the fixed-point loss.
2. For the demo subject (config.DEMO_SUBJECT) write everything the Verilog
   needs:
     rtl/params/neuroedge_params.vh   formats + trained scalars
     rtl/params/f_init.vh, g_init.vh, lut_init.vh   memory contents
     vectors/enc_*, cov_*, ns_*, top_*   test vectors for every testbench

Outputs: results/06_hardware_model.csv
"""
import numpy as np

from neuroedge import config as cfg, fixed as fx, pipeline as pl
from neuroedge.common import ROOT, out_path, parse_args, write_csv
from neuroedge.data import RAW_SAMPLES, WARMUP
from neuroedge.decoder import CSPLDA

PARAMS = ROOT / "rtl" / "params"
VEC = ROOT / "vectors"
N_TOP_TRIALS = 32     # trials simulated by tb_top (about 2 M clock cycles)
N_UNIT_TRIALS = 2     # trials used by the encoder / covariance unit tests


# ------------------------------------------------------------ float reference
def float_oracle(R1, y1, R2, y2):
    """Same decoder in floating point (exact alignment, natural log, float LDA),
    aligned with all of day 2: measures the fixed-point loss."""
    m = CSPLDA(n_filters=cfg.N_FILT, aligned=True).fit(R1.astype(float), y1)
    return float((m.predict(R2.astype(float)) == y2).mean())


# ------------------------------------------------------------ hex writing
def hexs(vals, width):
    digits = (width + 3) // 4
    mask = (1 << width) - 1
    return "\n".join(f"{int(v) & mask:0{digits}X}" for v in np.ravel(vals)) + "\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def vlit(v, width):
    """Signed Verilog literal, e.g. -24'sd123."""
    v = int(v)
    return f"{'-' if v < 0 else ''}{width}'sd{abs(v)}"


def mem_init(name, vals, width):
    return "\n".join(f"{name}[{i}] = {vlit(v, width)};" for i, v in enumerate(np.ravel(vals))) + "\n"


# ------------------------------------------------------------ export
def export_params(p, subject, synthetic=False):
    ints = {
        "N_CH": cfg.N_CH, "DATA_W": cfg.DATA_W,
        "M_FRAC": cfg.M_FRAC, "M_W": cfg.M_W, "M_SHIFT": cfg.M_SHIFT,
        "K_FRAC": cfg.K_FRAC, "K_INT": p["K_int"],
        "ACC_SUM_W": cfg.ACC_SUM_W, "COV_W": cfg.COV_W,
        "DRIFT_RN": cfg.DRIFT_RN, "DRIFT_RD": cfg.DRIFT_RD, "BURST_MAX": cfg.BURST_MAX,
        "NS_W": cfg.NS_W, "NS_FRAC": cfg.NS_FRAC, "NS_ITERS": p["iters"], "RSUM_W": cfg.RSUM_W,
        "N_FILT": cfg.N_FILT, "G_W": cfg.G_W, "CPRIME_W": cfg.CPRIME_W,
        "LOG_FRAC": cfg.LOG_FRAC, "LOG_MANT": cfg.LOG_MANT,
        "LDA_W_W": cfg.LDA_W_W, "SCORE_W": cfg.SCORE_W,
        "CS": p["CS"], "K_INIT": p["k1"], "WARMUP": WARMUP, "TRIAL_LEN": RAW_SAMPLES,
    }
    lines = ["// Auto-generated by python/06_hardware_model.py -- do not edit by hand",
             (f"// SYNTHETIC toy data (subject {subject}) -- run 06 on real data before reporting"
              if synthetic else f"// Trained parameters for BCI IV-2a subject {subject}"),
             *(f"localparam integer {k} = {v};" for k, v in ints.items())]
    for i, w in enumerate(p["w_int"]):
        lines.append(f"localparam signed [{cfg.LDA_W_W - 1}:0] LDA_W{i} = {vlit(w, cfg.LDA_W_W)};")
    lines.append(f"localparam signed [{cfg.SCORE_W - 1}:0] LDA_B = {vlit(p['b_int'], cfg.SCORE_W)};")
    for c, m in enumerate(p["m_ref"]):
        lines.append(f"localparam [{cfg.M_W - 1}:0] M_REF{c} = {cfg.M_W}'d{int(m)};")
    write(PARAMS / "neuroedge_params.vh", "\n".join(lines) + "\n")
    write(PARAMS / "f_init.vh", mem_init("f_mem", p["F_int"], cfg.G_W))
    write(PARAMS / "g_init.vh", mem_init("g_mem", p["G1"], cfg.G_W))
    write(PARAMS / "lut_init.vh", mem_init("lut", fx.LUT, cfg.LOG_FRAC + 2))


def export_vectors(p, prep, fe, run):
    K = int(p["K_int"])
    # ---- encoder + covariance unit vectors (first trials of day 2, from reset)
    Xf2 = prep["Xf2"].astype(np.int64)
    rec = fx.frontend_session(Xf2[:N_UNIT_TRIALS], [K], p["m_ref"], record=True)
    x_frames = Xf2[:N_UNIT_TRIALS].transpose(0, 2, 1).reshape(-1, cfg.N_CH)
    fire = rec["trace"]["mask"].astype(int)
    write(VEC / "enc_in.hex", hexs(x_frames, 16))
    write(VEC / "enc_fire.hex", hexs(fire, 1))
    cov_in = (fire << 16) | (x_frames & 0xFFFF)
    write(VEC / "cov_in.hex", hexs(cov_in, 17))
    write(VEC / "cov_R.hex", hexs(rec["R"][0], cfg.COV_W))
    write(VEC / "cov_macs.hex", hexs(np.cumsum(rec["macs"][0]), 32))
    write(VEC / "cov_events.hex", hexs(np.cumsum(rec["events"][0].sum(axis=1)), 32))

    # ---- calibration unit: forced drift at trial 0, burst over 16 trials
    R2 = fe["R2"][0]
    Rsum = np.zeros_like(R2[0])
    ks, gs = [], []
    for n in range(1, 17):
        Rsum = Rsum + R2[n - 1]
        if n & (n - 1) == 0:
            Z, k = fx.ns_calibrate(Rsum, n.bit_length() - 1, p["iters"])
            ks.append(k)
            gs.append(fx.g_from(p["F_int"], Z))
    write(VEC / "ns_R.hex", hexs(R2[:16], cfg.COV_W))
    write(VEC / "ns_k.hex", hexs(ks, 8))
    write(VEC / "ns_g.hex", hexs(np.array(gs), cfg.G_W))

    # ---- full system: raw samples in, decisions out
    T = N_TOP_TRIALS
    X2 = prep["X2"][:T].astype(np.int64).transpose(0, 2, 1).reshape(-1, cfg.N_CH)
    write(VEC / "top_in.hex", hexs(X2, 16))
    dec = run["preds"][:T]
    flags = [(2 if t in run["drift_at"] else 0) | (1 if t in run["recal_at"] else 0) for t in range(T)]
    write(VEC / "top_dec.hex", hexs(dec, 1))
    write(VEC / "top_score.hex", hexs(run["scores"][:T], cfg.SCORE_W))
    write(VEC / "top_flags.hex", hexs(flags, 2))
    write(VEC / "top_events.hex", hexs(np.cumsum(fe["events2"][0][:T].sum(axis=1)), 32))
    write(VEC / "top_macs.hex", hexs(np.cumsum(fe["macs2"][0][:T]), 32))
    write(VEC / "top_labels.hex", hexs(prep["y2"][:T], 1))
    print(f"Top-level vectors: {T} trials, {int(np.sum(dec == prep['y2'][:T]))}/{T} correct, "
          f"drift at {[t for t in run['drift_at'] if t < T]}, recal at {[t for t in run['recal_at'] if t < T]}")


def main():
    args = parse_args(__doc__, lambda ap: ap.add_argument("--K", type=float, default=cfg.K_DEFAULT))
    rows, demo = [], None
    frame_macs = fx.frame_based_macs(RAW_SAMPLES - WARMUP)
    for s in args.subjects:
        fe = pl.run_frontend(s, [args.K], args.synthetic)
        p = pl.train(fe["R1"][0], fe["y1"], fe["m_final1"][0], fe["K_ints"][0])
        run = pl.run_day2(p, fe["R2"][0], fe["m_end2"][0], fe["y2"], "drift")
        never = pl.run_day2(p, fe["R2"][0], fe["m_end2"][0], fe["y2"], "never")
        fixed_or = pl.run_day2(p, fe["R2"][0], fe["m_end2"][0], fe["y2"], "oracle")
        flt_or = float_oracle(fe["R1"][0], fe["y1"], fe["R2"][0], fe["y2"])
        n_win = fe["events2"].shape[1] * (RAW_SAMPLES - WARMUP) * cfg.N_CH
        rows.append(dict(subject=s, train_acc=p["train_acc"], never=never["acc"],
                         neuroedge=run["acc"], recals=run["n_recal"],
                         fixed_oracle=fixed_or["acc"], float_oracle=flt_or,
                         event_rate=float(fe["events2"][0].sum() / n_win),
                         mac_reduction=float(frame_macs / fe["macs2"][0].mean())))
        r = rows[-1]
        print(f"S{s}: never {r['never']:.1%} -> NeuroEdge {r['neuroedge']:.1%} ({r['recals']} recals), "
              f"oracle fixed {r['fixed_oracle']:.1%} / float {r['float_oracle']:.1%}, "
              f"events {r['event_rate']:.0%}, MACs {r['mac_reduction']:.1f}x fewer")
        if s == cfg.DEMO_SUBJECT:
            demo = (p, fe, run, s)

    keys = ["never", "neuroedge", "fixed_oracle", "float_oracle", "event_rate", "mac_reduction"]
    mean = {k: np.mean([r[k] for r in rows]) for k in keys}
    print("\nMean: " + "  ".join(f"{k} {mean[k]:.3f}" for k in keys))
    print(f"Fixed-point loss (float oracle - fixed oracle): "
          f"{(mean['float_oracle'] - mean['fixed_oracle']) * 100:.1f} points")
    write_csv(out_path("06_hardware_model", args.synthetic, "csv"), rows)

    if demo is None:
        print(f"Demo subject {cfg.DEMO_SUBJECT} not in --subjects: RTL files not written")
        return
    p, fe, run, s = demo
    export_params(p, s, args.synthetic)
    export_vectors(p, pl.prepare_subject(s, args.synthetic), fe, run)
    print(f"Wrote rtl/params/*.vh and vectors/* for subject {s}"
          + ("  (SYNTHETIC: rerun without --synthetic for real parameters)" if args.synthetic else ""))


if __name__ == "__main__":
    main()
